-- Procurement Deck (Inventory section) -- a page per slide of the monthly
-- "Monthly Procurement Update" exec deck (Executive Summary, Ending
-- Inventory Balance, COGS, RelaDyne/Valvoline/Mighty purchase activity and
-- fulfillment, 3-Way PO Match, and the Appendix's month-end count
-- compliance slides), each with an editable table, a file upload to
-- add/update it, and a chart matching the deck's own visual.
--
-- One flexible schema covers every slide shape instead of one table per
-- slide: most slides are a row x column grid (a metric by month, an Area
-- Manager by month, a market by KPI column) -- procurement_deck_grid_cells
-- treats "column" generically as col_key/col_label so a month axis and a
-- plain metric-name axis use the exact same shape. Snapshot KPI tiles
-- (Contract to Date, Est Fulfillment, etc. -- no month axis) and ordered
-- bullet lists (Wins/Opportunities, shops still open) get their own small
-- tables since forcing those into the grid shape would need a NULL/sentinel
-- column key for no real reason.
CREATE TABLE IF NOT EXISTS inventory.procurement_deck_grid_cells (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id   uuid        NOT NULL,
  slide_key    text        NOT NULL,
  table_key    text        NOT NULL,
  row_label    text        NOT NULL,
  row_sort     integer     NOT NULL DEFAULT 0,
  col_key      text        NOT NULL,
  col_label    text        NOT NULL,
  col_sort     integer     NOT NULL DEFAULT 0,
  value_num    numeric,
  value_text   text,
  updated_by   uuid,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, slide_key, table_key, row_label, col_key)
);

CREATE TABLE IF NOT EXISTS inventory.procurement_deck_kpis (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id   uuid        NOT NULL,
  slide_key    text        NOT NULL,
  table_key    text        NOT NULL,
  kpi_key      text        NOT NULL,
  label        text        NOT NULL,
  value_text   text,
  sort_order   integer     NOT NULL DEFAULT 0,
  updated_by   uuid,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, slide_key, table_key, kpi_key)
);

CREATE TABLE IF NOT EXISTS inventory.procurement_deck_list_items (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id   uuid        NOT NULL,
  slide_key    text        NOT NULL,
  table_key    text        NOT NULL,
  item_text    text        NOT NULL DEFAULT '',
  sort_order   integer     NOT NULL DEFAULT 0,
  updated_by   uuid,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_procurement_deck_grid_cells_slide ON inventory.procurement_deck_grid_cells (company_id, slide_key, table_key);
CREATE INDEX IF NOT EXISTS idx_procurement_deck_kpis_slide ON inventory.procurement_deck_kpis (company_id, slide_key, table_key);
CREATE INDEX IF NOT EXISTS idx_procurement_deck_list_items_slide ON inventory.procurement_deck_list_items (company_id, slide_key, table_key);

