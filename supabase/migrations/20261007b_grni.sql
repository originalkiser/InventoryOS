-- GRNI (Goods Received Not Invoiced) module. Replaces the "Open Order & Invoice Cut-off Analysis" workbook: a month-end run takes the
-- RelaDyne Open Sales Order report, the Open Invoice report, Droptop's PO receipts and each shop's receiving compliance and values what
-- has been delivered but not yet billed — the amount finance adds to expected on hand to tie out to Droptop.
--
-- A run snapshots its own copy of both uploaded reports (unlike inventory.rd_open_orders / rd_open_invoices, which are replaced on every
-- upload) so a month-end run can be reopened and re-calculated later.

-- RelaDyne price list, effective-dated (orders are priced at the price in effect on their order date).
CREATE TABLE IF NOT EXISTS inventory.grni_product_prices (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id     uuid NOT NULL,
  item_code      text NOT NULL,          -- RelaDyne ProductCode
  item_id        text,                   -- our product id (what Droptop calls it)
  description    text,
  uom            text,
  category       text,
  pkg_qty_gal    numeric NOT NULL,       -- gallons in one package (1 for bulk)
  price_gal      numeric NOT NULL,       -- price per gallon
  effective_from date NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (company_id, item_code, effective_from)
);

CREATE TABLE IF NOT EXISTS inventory.grni_runs (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id           uuid NOT NULL,
  period_month         date NOT NULL,     -- first day of the month being closed
  cutoff_date          date NOT NULL,     -- orders placed after this are not expected to be delivered by month end
  bulk_pct             numeric NOT NULL DEFAULT 0.9,
  package_pct          numeric NOT NULL DEFAULT 0.64,
  prior_pct            numeric NOT NULL DEFAULT 0.9,
  compliance_threshold numeric NOT NULL DEFAULT 0.8,
  orders_uploaded_at   timestamptz,
  invoices_uploaded_at timestamptz,
  notes                text,
  created_by           uuid,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS inventory.grni_open_orders (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id         uuid NOT NULL,
  company_id     uuid NOT NULL,
  order_date     date,
  sales_order_no text,
  customer_po_no text,
  ship_to_name   text,
  shop           integer,
  product_code   text NOT NULL,
  product_desc   text,
  qty_ordered    numeric NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_grni_open_orders_run ON inventory.grni_open_orders (run_id);

CREATE TABLE IF NOT EXISTS inventory.grni_open_invoices (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id          uuid NOT NULL,
  company_id      uuid NOT NULL,
  invoice_no      text,
  sales_order_no  text,
  customer_po_no  text,
  order_date      date,
  ship_date       date,
  invoice_date    date,
  ship_to_name    text,
  shop            integer,
  product_code    text NOT NULL,
  product_desc    text,
  qty_ordered     numeric NOT NULL DEFAULT 0,
  qty_shipped     numeric NOT NULL DEFAULT 0,
  gallons_ordered numeric NOT NULL DEFAULT 0,
  gallons_shipped numeric NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_grni_open_invoices_run ON inventory.grni_open_invoices (run_id);

-- Receiving compliance per shop for the run: receipts in Droptop as a share of what RelaDyne invoiced. A shop under the run's threshold
-- is not trusted to receive, so its open orders use the standard percentage assumptions instead of its receipts.
CREATE TABLE IF NOT EXISTS inventory.grni_shop_compliance (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id       uuid NOT NULL,
  company_id   uuid NOT NULL,
  shop         integer NOT NULL,
  shop_label   text,
  invoiced_gal numeric,
  received_gal numeric,
  pct          numeric,                   -- received / invoiced; null = no invoices to compare with
  source       text NOT NULL DEFAULT 'computed',  -- 'computed' (from Droptop) | 'upload' (PO Match export)
  override     text,                      -- null = by threshold | 'standard' = always assume | 'receipts' = always use receipts
  UNIQUE (run_id, shop)
);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['grni_product_prices', 'grni_runs', 'grni_open_orders', 'grni_open_invoices', 'grni_shop_compliance'] LOOP
    EXECUTE format('ALTER TABLE inventory.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON inventory.%I', t || '_select', t);
    EXECUTE format('CREATE POLICY %I ON inventory.%I FOR SELECT USING (company_id = (SELECT company_id FROM platform.user_profiles WHERE id = auth.uid()))', t || '_select', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON inventory.%I', t || '_manage', t);
    EXECUTE format('CREATE POLICY %I ON inventory.%I FOR ALL USING (company_id = (SELECT company_id FROM platform.user_profiles WHERE id = auth.uid())) WITH CHECK (company_id = (SELECT company_id FROM platform.user_profiles WHERE id = auth.uid()))', t || '_manage', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON inventory.%I TO authenticated', t);
  END LOOP;
END $$;

